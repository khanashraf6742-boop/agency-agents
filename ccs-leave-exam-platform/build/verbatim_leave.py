    "(b) the date of his final cessation of duties, or\n"
    "(c) the date on which he retires by giving notice to Government or he is retired by Government by giving him "
    "notice or pay and allowances in lieu of such notice, in accordance with the terms and conditions of his "
    "service, or\n"
    "(d) the date of his resignation from service.\n"
    "(2)(a) Where a Government servant retires on attaining the normal age prescribed for retirement under the "
    "terms and conditions governing his service, the authority competent to grant leave shall, suo motu, issue an "
    "order granting cash equivalent of leave salary for both earned leave and half pay leave, if any, at the "
    "credit of the Government servant on the date of his retirement subject to a maximum of 300 days;\n"
    "(b) The cash equivalent of leave salary under Clause (a) shall be calculated as follows and shall be payable "
    "in one lumpsum as a one-time settlement,\u2014\n"
    "(i) Cash equivalent for earned leave = [(Pay admissible on the date of retirement plus Dearness Allowance "
    "admissible on that date) \u00f7 30] \u00d7 Number of days of unutilized earned leave at credit subject to "
    "the total of earned leave and half pay leave not exceeding 300 days;\n"
    "(ii) Cash payment in lieu of half pay leave component = [(Half pay leave salary admissible on the date of "
    "retirement plus Dearness Allowance admissible on that date) \u00f7 30] \u00d7 Number of days of half pay "
    "leave at credit subject to the total of earned leave and half pay leave at credit not exceeding 300 days.\n"
    "NOTE.\u2014 The overall limit for encashment of leave including both earned leave and half pay leave shall "
    "not exceed 300 days.\n"
    "(c) To make up the shortfall in earned leave, no commutation of half pay leave shall be permissible.\n"
    "(DOPT Notification No. 11012/1/2009-Estt.(L), dated 01.12.2009)"
